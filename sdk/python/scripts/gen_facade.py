"""Render src/paladin/facade.py: one class per plane, sync and async, holding a
client for every service the contract defines on that plane.

The services come from the generated descriptors, not a list, so a service
added to the contract appears on regeneration, and tests/test_facade.py fails
until it is regenerated. Run from generate.sh, or directly.
"""

from __future__ import annotations

import importlib
import pkgutil
import re
import sys
from pathlib import Path

# Plane class prefix, Python package of the plane's generated modules.
PLANES = (("Data", "paladin.data.v1"), ("Admin", "paladin.admin.v1"), ("IAM", "paladin.iam.v1"))
SERVICE_SUFFIX = "Service"
DESCRIPTOR_MODULE_SUFFIX = "_pb2"
CONNECT_MODULE_SUFFIX = "_connect"
OUTPUT = Path(__file__).resolve().parents[1] / "src" / "paladin" / "facade.py"
_WORD_BOUNDARY = re.compile(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])")


def attribute(service: str) -> str:
    """The plane's attribute for a service: ``APITokenService`` → ``api_token``."""
    return _WORD_BOUNDARY.sub("_", service.removesuffix(SERVICE_SUFFIX)).lower()


def services(package: str) -> list[tuple[str, str]]:
    """(service name, connect module) for every service in ``package``, sorted."""
    found = []
    pkg = importlib.import_module(package)
    for info in pkgutil.iter_modules(pkg.__path__):
        if not info.name.endswith(DESCRIPTOR_MODULE_SUFFIX):
            continue
        module = importlib.import_module(f"{package}.{info.name}")
        stem = info.name.removesuffix(DESCRIPTOR_MODULE_SUFFIX)
        for name in module.DESCRIPTOR.services_by_name:
            found.append((name, f"{package}.{stem}{CONNECT_MODULE_SUFFIX}"))
    return sorted(found)


def render() -> str:
    lines = [
        "# Code generated by scripts/gen_facade.py. DO NOT EDIT.",
        '"""A client for every service of each plane; built by ``paladin.connect``."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
    ]
    planes = [(prefix, services(package)) for prefix, package in PLANES]
    for prefix, svcs in planes:
        if not svcs:
            raise SystemExit(f"gen_facade: no services for the {prefix} plane")
        for name, module in svcs:
            lines.append(f"from {module} import {name}Client, {name}ClientSync")
    for prefix, svcs in planes:
        for kind, suffix in (("", "Sync"), ("Async", "")):
            lines += [
                "",
                "",
                f"class {kind}{prefix}Plane:",
                f'    """Every service of the {prefix.lower()} plane."""',
                "",
                "    def __init__(self, address: str, interceptors: Any, **options: Any) -> None:",
            ]
            for name, _ in svcs:
                lines.append(
                    f"        self.{attribute(name)} = {name}Client{suffix}"
                    "(address, interceptors=interceptors, **options)"
                )
    lines += ["", "", "SERVICES = {"]
    for prefix, svcs in planes:
        lines.append(f'    "{prefix}": {tuple(n for n, _ in svcs)!r},')
    lines += ["}", '"""The services each plane holds, for tests."""', ""]
    return "\n".join(lines)


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else OUTPUT
    out.write_text(render())
