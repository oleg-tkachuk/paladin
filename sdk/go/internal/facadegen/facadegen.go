// Package facadegen renders paladin/facade_gen.go: one struct per plane that
// holds a client for every service the contract defines on it.
//
// The services come from the linked descriptors, not a list, so a service
// added to the contract appears in the facade on regeneration, and
// TestFacadeIsGenerated fails until it is regenerated.
package facadegen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/reflect/protoregistry"

	// Linked so the registry holds every service of the three planes.
	_ "github.com/oleg-tkachuk/paladin/sdk/go/gen/paladin/admin/v1"
	_ "github.com/oleg-tkachuk/paladin/sdk/go/gen/paladin/data/v1"
	_ "github.com/oleg-tkachuk/paladin/sdk/go/gen/paladin/iam/v1"
)

// Plane is one listener of the server and the proto package served on it.
type Plane struct {
	// Name is the plane as the facade spells it: the struct is <Name>Plane.
	Name string
	// Package is the proto package of the plane's services.
	Package protoreflect.FullName
	// ConnectImport is the Go package of the plane's generated Connect clients.
	ConnectImport string
	// Transfers is whether the plane moves bytes through presigned URLs, and
	// so carries the client's Transfer for Upload and Download.
	Transfers bool
}

// connectImportPrefix is where buf generates the Connect clients.
const connectImportPrefix = "github.com/oleg-tkachuk/paladin/sdk/go/gen/paladin/"

// Planes are the three planes, in the order the facade declares them.
var Planes = []Plane{
	{Name: "Data", Package: "paladin.data.v1", ConnectImport: connectImportPrefix + "data/v1/paladindatav1connect", Transfers: true},
	{Name: "Admin", Package: "paladin.admin.v1", ConnectImport: connectImportPrefix + "admin/v1/paladinadminv1connect"},
	{Name: "IAM", Package: "paladin.iam.v1", ConnectImport: connectImportPrefix + "iam/v1/paladiniamv1connect"},
}

// serviceSuffix is dropped from a service's name to name its facade field.
const serviceSuffix = "Service"

// Services returns the service names the contract defines in pkg, sorted.
func Services(pkg protoreflect.FullName) []string {
	var names []string
	protoregistry.GlobalFiles.RangeFilesByPackage(pkg, func(fd protoreflect.FileDescriptor) bool {
		for i := range fd.Services().Len() {
			names = append(names, string(fd.Services().Get(i).Name()))
		}
		return true
	})
	sort.Strings(names)
	return names
}

// Field is the facade's field name for a service.
func Field(service string) string {
	return strings.TrimSuffix(service, serviceSuffix)
}

// Render returns the formatted source of facade_gen.go.
func Render() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/facadegen. DO NOT EDIT.\n\npackage paladin\n\nimport (\n")
	for _, p := range Planes {
		fmt.Fprintf(&b, "\t%q\n", p.ConnectImport)
	}
	b.WriteString(")\n")
	for _, p := range Planes {
		services := Services(p.Package)
		if len(services) == 0 {
			return nil, fmt.Errorf("facadegen: no services in %s", p.Package)
		}
		alias := p.ConnectImport[strings.LastIndex(p.ConnectImport, "/")+1:]
		fmt.Fprintf(&b, "\n// %sPlane holds a client for every service of the %s plane.\ntype %sPlane struct {\n", p.Name, strings.ToLower(p.Name), p.Name)
		for _, s := range services {
			fmt.Fprintf(&b, "\t%s %s.%sClient\n", Field(s), alias, s)
		}
		if p.Transfers {
			b.WriteString("\n\ttransfer *Transfer\n")
		}
		fmt.Fprintf(&b, "}\n\nfunc new%sPlane(c *Client) *%sPlane {\n\treturn &%sPlane{\n", p.Name, p.Name, p.Name)
		for _, s := range services {
			fmt.Fprintf(&b, "\t\t%s: %s.New%sClient(c.httpClient, c.baseURL, c.ClientOptions()...),\n", Field(s), alias, s)
		}
		if p.Transfers {
			b.WriteString("\t\ttransfer: c.transfer,\n")
		}
		b.WriteString("\t}\n}\n")
	}
	return format.Source(b.Bytes())
}
